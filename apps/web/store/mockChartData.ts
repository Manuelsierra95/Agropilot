/**
 * Devuelve datos de chart ajustados para una parcela específica.
 * Aplica factores de variación para simular que cada parcela
 * tiene métricas diferentes.
 */
export function getChartDataForParcel(parcelId: string) {
  const factors = parcelFactors[parcelId] ?? parcelFactors["1"]!

  return chartData.map((entry) => ({
    date: entry.date,
    precioOliva:
      Math.round(
        (entry.precioOliva * factors.precioOliva + factors.offset) * 100
      ) / 100,
    rendimiento: Math.min(
      100,
      Math.max(0, Math.round(entry.rendimiento * factors.rendimiento))
    ),
    lluvias: Math.max(0, Math.round(entry.lluvias * factors.lluvias * 10) / 10),
    cosechaAnterior: Math.round(
      entry.cosechaAnterior * factors.cosechaAnterior
    ),
  }))
}

